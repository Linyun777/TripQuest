/** Just enough of the S5.3 repositories, in memory, so no database is involved. */
class MemoryJourneys implements GeneratedDayRepository, DayProgressRepository {
  private readonly journeys = new Map<string, StoredJourney>();
  private readonly creations = new Map<string, { journeyId: string; intentFingerprint: string }>();

  async createInitialJourney(): Promise<void> {
    throw new Error("Manual journeys are not part of the S5.4 evaluation");
  }

  async findCurrentJourney(journeyId: string): Promise<StoredJourney | null> {
    return this.journeys.get(journeyId) ?? null;
  }

  async findGeneratedDayCreation(runId: string) {
    return this.creations.get(runId) ?? null;
  }

  async createGeneratedDay(draft: InitialGeneratedDayDraft) {
    this.creations.set(draft.creationRunId, {
      journeyId: draft.journeyId,
      intentFingerprint: draft.creationIntentFingerprint,
    });
    this.journeys.set(draft.journeyId, {
      creationKind: "generated_day",
      dayDetails: draft.dayDetails,
      journeyId: draft.journeyId,
      title: draft.title,
      createdAt: draft.createdAt,
      updatedAt: draft.updatedAt,
      currentObservationVersion: 0,
      currentPlan: draft.currentPlan,
      activitySnapshots: draft.activitySnapshots,
      reservations: draft.reservations,
    });
    return { status: "saved" as const, journeyId: draft.journeyId, planVersion: 1 as const };
  }

  async findDayProgressReport() {
    return null;
  }

  async commitDayProgress(command: {
    journeyId: string;
    command: DayProgressCommand;
    intentFingerprint: string;
    recordedAt: ChinaDateTime;
  }): Promise<DayProgressReply> {
    const stored = this.journeys.get(command.journeyId)!;
    const checked = checkDayProgress(stored, command.command, command.intentFingerprint);
    if (checked.status !== "ready") return checked;
    this.journeys.set(command.journeyId, {
      ...stored,
      currentObservationVersion: checked.next.version,
      dayProgress: { ...checked.next, recordedAt: command.recordedAt },
    });
    return { status: "saved", observationVersion: checked.next.version };
  }
}

const clock = { now: () => new Date(S54_NOW) };
const ids = { next: () => randomUUID() };

/** The saved v1 day a replan case starts from, generated by the scripted S5.2 heuristic. */
async function saveBaseDay(repository: MemoryJourneys, base: ReplanCase["base"]): Promise<StoredJourney> {
  const requirements = BASE_DAYS[base];
  const problem = createDayPlanningProblem({
    requirements,
    runId: randomUUID(),
    requirementsFingerprint: fingerprintRequirements(requirements),
    nowMs: S54_NOW,
  });
  let snapshot: DayDraftConfirmationSnapshot | undefined;
  const result: DayPlanningResult = await createDayPlanningRunner({
    provider: new PlanningFixtureProvider(() => S54_NOW),
    model: createDayScriptedModel(),
    now: () => S54_NOW,
  }).run(problem, {
    signal: new AbortController().signal,
    onProgress: () => {},
    onDraftReady: (ready) => {
      snapshot = ready;
    },
  });
  if (result.status !== "completed" || result.outcome !== "draft" || !snapshot) {
    throw new Error(`Base day ${base} could not be generated`);
  }
  const saved = await confirmGeneratedDay({
    snapshot,
    draftFingerprint: dayDraftSemanticFingerprint(snapshot),
    title: `S5.4 基础行程 ${base}`,
    acknowledgeUnknowns: true,
    expiresAt: S54_NOW + 15 * 60_000,
    enabled: true,
    repository,
    idGenerator: ids,
    clock,
  });
  if (saved.status !== "saved") throw new Error(`Base day ${base} could not be saved: ${saved.status}`);
  return (await repository.findCurrentJourney(saved.journeyId))!;
}

const clockMinutes = (iso: string) => Number(iso.slice(11, 13)) * 60 + Number(iso.slice(14, 16));
const reported = (minutes: number): string =>
  `${S54_PLAN_DATE}T${String(Math.floor(minutes / 60)).padStart(2, "0")}:${String(minutes % 60).padStart(2, "0")}+08:00`;

/** Applies the case's progress spec to the saved plan, in plan order. */
function progressCommand(stored: StoredJourney, spec: ReplanCase["progress"]): DayProgressCommand {
  const activities = stored.currentPlan.activities;
  const firstFixed = activities.findIndex((item) => item.locked);
  const count = {
    none: 0,
    first: 1,
    all: activities.length,
    before_fixed: firstFixed < 0 ? activities.length : firstFixed,
  }[spec.complete];
  const completed = activities.slice(0, count);
  const skipped = spec.skip === "required"
    ? activities.filter((item) => item.priority === "high" && !item.locked).slice(0, 1)
    : [];
  const last = completed.at(-1);
  const time = (value: string) => value.startsWith("+")
    ? reported(clockMinutes(last!.endsAt) + Number(value.slice(1)))
    : `${S54_PLAN_DATE}T${value}+08:00`;
  const details = stored.dayDetails!;
  if (details.schemaVersion !== "stored-day-plan.v1") throw new Error("Base day must be v1");
  const startPlace = details.placeBindings.find((binding) =>
    binding.draftPlaceId === details.planning.problem.input.startPlaceId)!.placeId;
  return {
    reportId: randomUUID(),
    basePlanVersion: stored.currentPlan.version,
    baseObservationVersion: stored.currentObservationVersion,
    completedActivityIds: completed.map((item) => item.id),
    skippedActivityIds: skipped.map((item) => item.id),
    observedAt: time(spec.observedAt),
    earliestResumeAt: time(spec.resumeAt),
    location: spec.location === "unknown"
      ? { kind: "unknown" }
      : { kind: "known", placeId: spec.location === "start" || !last ? startPlace : last.placeId },
    noCurrentActivity: true,
  };
}

export interface PreparedReplan {
  readonly base: StoredJourney;
  readonly preparation: ReplanPreparation;
}

/** Saved v1 → reported progress → the frozen replan problem (or the preflight refusal). */
export async function prepareReplanCase(item: ReplanCase): Promise<PreparedReplan> {
  const repository = new MemoryJourneys();
  const base = await saveBaseDay(repository, item.base);
  const reply = await reportDayProgress({
    journeyId: base.journeyId,
    command: progressCommand(base, item.progress),
    enabled: true,
    now: S54_NOW,
    repository,
  });
  if (reply.status !== "saved") throw new Error(`Progress for ${item.id} was not saved: ${reply.status}`);
  const stored = (await repository.findCurrentJourney(base.journeyId))!;
  const preparation = prepareDayReplan(stored, {
    runId: randomUUID(),
    scope: item.scope,
    goal: item.goal,
    nowMs: S54_NOW,
    basePlanVersion: stored.currentPlan.version,
    baseObservationVersion: stored.currentObservationVersion,
    original: originalContextOf(stored),
  });
  return { base, preparation };
}
