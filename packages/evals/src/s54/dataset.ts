/**
 * S5.4 hand-authored cases. Fixture walking minutes between catalogue positions i → j are
 * ceil((240 + 120·|i−j| + (i > j ? 61 : 1)) / 60): |Δ|=1 → 7/8, 2 → 9/10, 3 → 11/12,
 * 4 → 13/14, 5 → 15/16 (forward/backward). Positions: START 0, MUSEUM-A 1, MUSEUM-B 2,
 * PARK 3, FOOD 4, GARDEN 5, WALK 6, CAFE 7. Buffer: standard 5, relaxed 10.
 * Expectations are acceptance rules written by hand, never copied from a run.
 */
export const S54_DATASET_VERSION = "s54-planning-eval.v1";
export const S54_PLAN_DATE = "2026-10-16";

/** must_plan: a usable result; must_refuse: an honest stop; either_honest: both, never a violation. */
export type Expectation = "must_plan" | "must_refuse" | "either_honest";

export interface DraftCase {
  readonly id: string;
  readonly flow: "draft";
  readonly title: string;
  readonly requirements: PlanningRequirements;
  readonly faults?: S54Faults;
  readonly expect: Expectation;
  /** Accepted no_plan reasons when the case must refuse. */
  readonly refuseReasons?: readonly string[];
  readonly minActivities?: number;
  readonly note: string;
}

export type BaseDay = "A" | "B";

export interface ProgressSpec {
  /** Activities of the saved v1 plan, by position, reported completed / skipped. */
  readonly complete: "first" | "all" | "before_fixed" | "none";
  readonly skip?: "required";
  readonly observedAt: string;
  readonly resumeAt: string;
  /** Where the traveller is: the last completed activity's place, the start, or unknown. */
  readonly location: "last_completed" | "start" | "unknown";
}

export interface ReplanCase {
  readonly id: string;
  readonly flow: "replan";
  readonly title: string;
  readonly base: BaseDay;
  readonly progress: ProgressSpec;
  readonly scope: ReplanScope;
  readonly goal: ReplanGoal;
  readonly faults?: S54Faults;
  readonly expect: Expectation;
  /** Accepted stop reasons: "preflight:<status|conflict>" or a bounded_no_candidate reason. */
  readonly refuseReasons?: readonly string[];
  /** less_walking: walking ≤ baseline; relaxed: activities or waiting ≤ baseline. */
  readonly goalCheck?: boolean;
  readonly note: string;
}

export type S54Case = DraftCase | ReplanCase;

type Visit = PlanningRequirements["visits"][number];
const optional = (id: FixturePlaceId, stayMinutes: number): Visit =>
  ({ place: selection(id), role: "optional", stayMinutes });
const required = (id: FixturePlaceId, stayMinutes: number): Visit =>
  ({ place: selection(id), role: "required", stayMinutes });
const fixed = (id: FixturePlaceId, startsAt: string, endsAt: string): Visit =>
  ({ place: selection(id), role: "fixed", startsAt, endsAt });

function requirements(options: {
  window: readonly [string, string];
  end: FixturePlaceId;
  interests: PlanningRequirements["interests"];
  pace?: PlanningRequirements["pace"];
  visits?: readonly Visit[];
}): PlanningRequirements {
  // Parsed once here: schema key order is what fingerprints and confirmation recompute.
  return planningRequirementsSchema.parse({
    schemaVersion: "planning-requirements.v1",
    cityAdcode: "330100",
    timeZone: "Asia/Shanghai",
    travelMode: "walking",
    date: S54_PLAN_DATE,
    window: { startsAt: options.window[0], endsAt: options.window[1] },
    startPlace: selection("DEMO-START"),
    endPlace: selection(options.end),
    interests: [...options.interests],
    pace: options.pace ?? "standard",
    visits: [...(options.visits ?? [])],
  });
}

