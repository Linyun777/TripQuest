export const S54_CASES: readonly S54Case[] = [...draftCases, ...replanCases];

/** SHA-256 over inputs, faults and expectations; editing any of them needs a new version. */
export function s54DatasetDigest(cases: readonly S54Case[] = S54_CASES): string {
  return createHash("sha256")
    .update(JSON.stringify({ version: S54_DATASET_VERSION, bases: BASE_DAYS, cases }))
    .digest("hex");
}
